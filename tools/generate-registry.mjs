import { CATEGORIES } from './fixture-names.mjs';
import { readFileSync, writeFileSync, copyFileSync } from 'fs';

const overridesFile = new URL('./status.json', import.meta.url);
const overrides = JSON.parse(readFileSync(overridesFile, 'utf8')).overrides ?? {};

const fixtures = [];
for (const cat of CATEGORIES) {
  const expected = cat.end - cat.start + 1;
  if (cat.names.length !== expected) {
    throw new Error(`Category ${cat.name}: ${cat.names.length} names, expected ${expected}`);
  }
  cat.names.forEach((name, i) => {
    const n = cat.start + i;
    const id = `MP-${String(n).padStart(3, '0')}`;
    const o = overrides[id] ?? {};
    fixtures.push({
      id,
      categoryId: CATEGORIES.indexOf(cat) + 1,
      category: cat.name,
      name,
      acceptanceCriteria: `${id}: ${name} must work end to end and be demonstrated by an automated test.`,
      implementationStatus: o.implementation ?? 'NOT_STARTED',
      testStatus: o.test ?? 'NOT_STARTED',
      dependencies: o.dependencies ?? [],
      note: o.note ?? null,
      evidence: { implementation: o.implementationEvidence ?? [], tests: o.testEvidence ?? [] }
    });
  });
}
if (fixtures.length !== 600) throw new Error(`Expected 600 fixtures, got ${fixtures.length}`);

const registry = {
  schemaVersion: 1,
  project: 'Messenger Pro',
  packageId: 'com.sikorokoro44.messengerpro',
  total: 600,
  categories: CATEGORIES.length,
  generatedFrom: 'tools/fixture-names.mjs',
  fixtures
};
writeFileSync(new URL('../feature-registry.json', import.meta.url), JSON.stringify(registry, null, 2) + '\n');
copyFileSync(new URL('../feature-registry.json', import.meta.url), new URL('../app/src/main/assets/feature-registry.json', import.meta.url));

// Emit a pure-Kotlin copy so the app and JVM tests do not need Android JSON parsing.
const kotlin = `package com.sikorokoro44.messengerpro.engine

// GENERATED by tools/generate-registry.mjs. Do not edit by hand.
enum class FixtureStatus { COMPLETE, IN_PROGRESS, NOT_STARTED, BLOCKED }

data class FixtureDef(
    val id: String,
    val category: String,
    val name: String,
    val implementation: FixtureStatus,
    val test: FixtureStatus
)

object RegistryData {
    val fixtures: List<FixtureDef> = listOf(
${fixtures.map(f => `        FixtureDef("${f.id}", ${JSON.stringify(f.category)}, ${JSON.stringify(f.name)}, FixtureStatus.${f.implementationStatus}, FixtureStatus.${f.testStatus})`).join(',\n')}
    )
}
`;
writeFileSync(new URL('../app/src/main/java/com/sikorokoro44/messengerpro/engine/RegistryData.kt', import.meta.url), kotlin);

const count = (s) => fixtures.filter(f => f.implementationStatus === s).length;
console.log(`Wrote ${fixtures.length} fixtures (${CATEGORIES.length} categories)`);
console.log(`implementation: COMPLETE=${count('COMPLETE')} IN_PROGRESS=${count('IN_PROGRESS')} NOT_STARTED=${count('NOT_STARTED')} BLOCKED=${count('BLOCKED')}`);
